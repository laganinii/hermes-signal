export function addCustomSource(
  s: Omit<NewsSource, 'userAdded'> & { userAdded?: boolean },
  existing: NewsSource[] = defaultSources
): NewsSource[] {
  const normalizedFeedUrl = normalizeCustomFeedUrl(s.feedUrl || s.url, s.type);
  const newSource: NewsSource = {
    ...s,
    feedUrl: normalizedFeedUrl,
    userAdded: true,
    enabled: s.enabled ?? true,
  };
  return [...existing.filter((item) => item.id !== newSource.id), newSource];
}

export function normalizeCustomFeedUrl(inputUrl: string, type?: NewsSource['type']): string {
  const trimmed = inputUrl.trim();
  if (!trimmed) return '';
  // Convert r/subreddit or reddit.com/r/subreddit to .rss automatically
  if (trimmed.startsWith('r/') || trimmed.startsWith('/r/')) {
    const sub = trimmed.replace(/^\/?r\//, '').replace(/\/+$/, '');
    return `https://www.reddit.com/r/${sub}/.rss`;
  }
  if (trimmed.includes('reddit.com/r/') && !trimmed.endsWith('.rss')) {
    return `${trimmed.replace(/\/+$/, '')}/.rss`;
  }
  if (!/^https?:\/\//i.test(trimmed)) {
    return `https://${trimmed}`;
  }
  return trimmed;
}
